#!/usr/bin/env python3
"""Generate the address -> lifted-function dispatcher for the Android target.

Unlike the historical Windows generator, this emits no Win32 includes, no
probe file and no `#ifdef WC3_DEBUG`.  The release dispatcher contains only the
lift table, the direct hash lookup and the HLE call bridge; unknown targets are
fatal instead of returning a fake value.

Usage:
  python tools/gen_dispatch.py build/lifted_list.h build/wc3_dispatch.c
"""
from __future__ import annotations

import os
import re
import sys
from pathlib import Path

HEADER = """/* AUTO-GENERATED by tools/gen_dispatch.py - do not edit */
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "cpu.h"
#include "guest_layout.h"
#include "hle_abi.h"

#ifndef WC3_DEBUG
#define WC3_DEBUG 0
#endif

#define X(a) void L_##a(CPU *c);
#include "@LIST@"
LIFTED_FUNCS(X)
#undef X

uint32_t g_image_delta = 0;

typedef struct LiftEnt {
    uint32_t va;
    void (*fn)(CPU *);
} LiftEnt;

static const LiftEnt g_lift[] = {
@ROWS@};

#define LIFT_HASH_BITS 19
#define LIFT_HASH_SIZE (1u << LIFT_HASH_BITS)
static uint32_t g_lift_hash[LIFT_HASH_SIZE];
static HleRegistry *g_hle_registry;

static inline void (*find_lifted(uint32_t va))(CPU *)
{
    uint32_t h = (va * 2654435761u) >> (32 - LIFT_HASH_BITS);
    for (unsigned n = 0; n < LIFT_HASH_SIZE; n++) {
        uint32_t e = g_lift_hash[h];
        if (!e) return NULL;
        if (g_lift[e - 1].va == va) return g_lift[e - 1].fn;
        h = (h + 1u) & (LIFT_HASH_SIZE - 1u);
    }
    return NULL;
}

void wc3_dispatch_init(HleRegistry *registry)
{
    g_hle_registry = registry;
    memset(g_lift_hash, 0, sizeof g_lift_hash);
    size_t count = sizeof g_lift / sizeof g_lift[0];
    for (size_t i = 0; i < count; i++) {
        uint32_t h = (g_lift[i].va * 2654435761u) >> (32 - LIFT_HASH_BITS);
        while (g_lift_hash[h]) h = (h + 1u) & (LIFT_HASH_SIZE - 1u);
        g_lift_hash[h] = (uint32_t)(i + 1u);
    }
}

void wc3_dispatch_shutdown(void)
{
    g_hle_registry = NULL;
    memset(g_lift_hash, 0, sizeof g_lift_hash);
}

static void dispatch_common(CPU *c, uint32_t target, int tail)
{
    int chained = 0;
    int have_fn = 0;
    void (*pending_fn)(CPU *) = NULL;
    (void)tail;
    if (!c) abort();
    c->disp_depth++;
    for (;;) {
        c->disp_pending_valid = 0;
        if (have_fn) {
            void (*fn)(CPU *) = pending_fn;
            have_fn = 0;
            pending_fn = NULL;
            fn(c);
        } else if (target >= GUEST_HLE_BASE &&
                   target < GUEST_HLE_BASE + (uint32_t)HLE_MAX * HLE_STRIDE) {
            if (!g_hle_registry) abort();
            hle_abi_call(g_hle_registry, target, c);
        } else {
            void (*fn)(CPU *) = find_lifted(target);
            if (!fn) {
#if WC3_DEBUG
                fprintf(stderr, "[dispatch] unknown guest target %08X (eip=%08X esp=%08X%s)\\n",
                        target, c->eip, c->esp, (tail || chained) ? " [jmp]" : "");
#endif
                abort();
            }
            fn(c);
        }
        if (!c->disp_pending_valid) break;
        chained = 1;
        if (c->disp_pending_kind == WC3_DISP_PENDING_FN) {
            pending_fn = (void (*)(CPU *))c->disp_pending_target;
            have_fn = 1;
        } else {
            target = (uint32_t)c->disp_pending_target;
        }
    }
    (void)chained;
    c->disp_depth--;
}

void dispatch(CPU *c, uint32_t target)
{
    dispatch_common(c, target, 0);
}

void dispatch_jmp(CPU *c, uint32_t target)
{
    if (c->disp_depth > 0) {
        c->disp_pending_valid = 1u;
        c->disp_pending_kind = WC3_DISP_PENDING_VA;
        c->disp_pending_target = target;
        return;
    }
    dispatch_common(c, target, 1);
}
"""


def main(argv: list[str] | None = None) -> int:
    if argv is None:
        argv = sys.argv[1:]
    if len(argv) != 2:
        print(__doc__)
        return 2
    src = Path(argv[0])
    dst = Path(argv[1])
    text = src.read_text(encoding="utf-8")
    addrs = re.findall(r"X\(([0-9A-Fa-f]{8})\)", text)
    if not addrs:
        print(f"{src}: no X(XXXXXXXX) entries", file=sys.stderr)
        return 1

    rows: list[int] = []
    seen: set[int] = set()
    for a in addrs:
        va = int(a, 16)
        if va in seen:
            continue
        seen.add(va)
        rows.append(va)
    rows.sort()

    row_text = "".join("    { 0x%08Xu, L_%08X },\n" % (va, va) for va in rows)
    output = HEADER.replace("@LIST@", src.name).replace("@ROWS@", row_text)
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(output, encoding="utf-8", newline="\n")
    print(f"{src}: {len(rows)} functions -> {dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
