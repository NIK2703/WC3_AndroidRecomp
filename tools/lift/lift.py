#!/usr/bin/env python3
"""Parallel lift and deterministic splitting for one PE module."""

from __future__ import annotations

import concurrent.futures
import hashlib
import os
import re
import shutil
from dataclasses import dataclass
from pathlib import Path

from . import LIFT_REV
from . import lifter32
from .discover import Entry
from .lifter32 import Lifter
from .pe_image import PeImage

FUNC_RE = re.compile(r"(?=^void L_[0-9A-F]{8}\(CPU \*c\))", re.MULTILINE)
DISPATCH_RE = re.compile(r"dispatch(?:_jmp)?\(c,\s*0x([0-9A-Fa-f]{8})u\)")


@dataclass
class LiftResult:
    catalog: list[Entry]
    c_path: Path
    chunks: list[Path]
    function_count: int
    c_sha256: str
    catalog_sha256: str


def _slice_entries(entries: list[Entry], jobs: int) -> list[list[Entry]]:
    if jobs <= 1 or len(entries) <= 1:
        return [entries]
    n = min(jobs, len(entries))
    # Balance by total bytes, not by entry count: a 64 KiB function costs far
    # more than a thunk, and the old tree's chunks were visibly unbalanced.
    total = sum(e.size for e in entries) or 1
    target = total / n
    out: list[list[Entry]] = []
    cur: list[Entry] = []
    cur_bytes = 0
    for e in entries:
        cur.append(e)
        cur_bytes += e.size
        if len(out) < n - 1 and cur_bytes >= target:
            out.append(cur)
            cur = []
            cur_bytes = 0
    if cur:
        out.append(cur)
    return out


def _work(args: tuple[str, list[Entry], str, bool, int]) -> tuple[str, list[int]]:
    image_path, entries, out_path, block, base = args
    os.environ["WC3_LIFT_BLOCK"] = "1" if block else "0"
    img = PeImage(image_path)
    if base and img.base != base:
        raise RuntimeError(f"{image_path}: base {img.base:#x} != {base:#x}")
    lifter32.IMAGE_BASE = img.base
    lifter = Lifter(image_path, img.image_size, img.read_va)
    lifter.reloc_vas = img.reloc_vas()
    path = Path(out_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    written: list[int] = []
    with path.open("w", encoding="utf-8", newline="\n") as f:
        for e in entries:
            if not img.is_code(e.va):
                continue
            code = img.read_va(e.va, e.size)
            f.write(lifter.lift_function(code, e.va))
            f.write("\n\n")
            written.append(e.va)
    return str(path), written


def _header(image: PeImage) -> str:
    return (
        f"/* AUTO-GENERATED by tools/lift (lift_rev={LIFT_REV}); do not edit. */\n"
        f"/* image: {image.path.name} sha256:{image.sha256()} */\n"
        f'#include "cpu.h"\n\n'
    )


def split_c(text: str, out_dir: Path, max_lines: int = 4000) -> list[Path]:
    """Split on emitted function definitions, never inside a function."""
    out_dir.mkdir(parents=True, exist_ok=True)
    marker = text.find("void L_")
    if marker < 0:
        return []
    head = text[:marker]
    body = text[marker:]
    parts = [p for p in FUNC_RE.split(body) if p.strip()]
    chunks: list[Path] = []
    cur: list[str] = []
    cur_lines = 0

    def flush() -> None:
        nonlocal cur, cur_lines
        if not cur:
            return
        p = out_dir / f"chunk_{len(chunks):04d}.c"
        p.write_text(head + "".join(cur), encoding="utf-8", newline="\n")
        chunks.append(p)
        cur = []
        cur_lines = 0

    for part in parts:
        n = part.count("\n")
        if cur and cur_lines + n > max_lines:
            flush()
        cur.append(part)
        cur_lines += n
    flush()
    return chunks


def write_list(vaddrs: list[int], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    ordered = sorted(set(vaddrs))
    with path.open("w", encoding="ascii", newline="\n") as f:
        f.write("/* AUTO-GENERATED by tools/lift; do not edit. */\n")
        f.write("#define LIFTED_FUNCS(X) \\\n")
        for i, va in enumerate(ordered):
            sep = "" if i + 1 == len(ordered) else " \\"
            f.write(f"    X({va:08X}){sep}\n")
        if not ordered:
            f.write("\n")


def lift_catalog(
    image_path: str | Path,
    entries: list[Entry],
    out_dir: str | Path,
    *,
    jobs: int = 4,
    block: bool = False,
    tag: str = "lift",
) -> LiftResult:
    image_path = str(Path(image_path).resolve())
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    parts_dir = out_dir / f".{tag}_parts"
    if parts_dir.exists():
        shutil.rmtree(parts_dir)
    parts_dir.mkdir(parents=True)
    parts = _slice_entries(entries, jobs)
    img = PeImage(image_path)
    jobs_list = [
        (image_path, part, str(parts_dir / f"part_{i:04d}.c"), block, img.base)
        for i, part in enumerate(parts)
    ]
    results: list[tuple[str, list[int]]] = []
    if len(jobs_list) <= 1:
        results.append(_work(jobs_list[0]))
    else:
        with concurrent.futures.ProcessPoolExecutor(max_workers=len(jobs_list)) as ex:
            futures = [ex.submit(_work, j) for j in jobs_list]
            for fut in futures:
                results.append(fut.result())
    results.sort(key=lambda item: item[0])
    catalog_path = out_dir / f"functions.{tag}.txt"
    with catalog_path.open("w", encoding="ascii", newline="\n") as f:
        for e in entries:
            f.write(e.line() + "\n")
    c_path = out_dir / f"{tag}.c"
    all_written: list[int] = []
    with c_path.open("w", encoding="utf-8", newline="\n") as out:
        out.write(_header(img))
        for part_path, vaddrs in results:
            out.write(Path(part_path).read_text(encoding="utf-8"))
            all_written.extend(vaddrs)
    write_list(all_written, out_dir / f"{tag}.list.h")
    digest = hashlib.sha256(c_path.read_bytes()).hexdigest()
    cat_digest = hashlib.sha256(catalog_path.read_bytes()).hexdigest()
    chunks = split_c(c_path.read_text(encoding="utf-8"), out_dir / "chunks")
    return LiftResult(
        catalog=entries,
        c_path=c_path,
        chunks=chunks,
        function_count=len(all_written),
        c_sha256=digest,
        catalog_sha256=cat_digest,
    )


def scan_targets(paths: list[Path] | list[str]) -> set[int]:
    out: set[int] = set()
    for p in paths:
        text = Path(p).read_text(encoding="utf-8", errors="replace")
        out.update(int(x, 16) for x in DISPATCH_RE.findall(text))
    return out
