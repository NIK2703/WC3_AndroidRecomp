#!/usr/bin/env python3
"""Lift one function catalog slice into a C translation unit.

This is the worker used by `tools/wc3lift.py` and by its process pool.  It is
deliberately a separate process: capstone and the emitter are CPU-bound, and a
crashed worker must not take the corpus manifest or the build directory with
it.

Usage:
  python -m tools.lift.lift_one --image <pe> --funcs <catalog.txt> --out <x.c>
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

from . import LIFT_REV
from .lifter32 import Lifter
from . import lifter32
from .pe_image import PeImage


def load_bounds(path: str | Path) -> list[tuple[int, int, str]]:
    out: list[tuple[int, int, str]] = []
    for lineno, raw in enumerate(Path(path).read_text(encoding="utf-8",
                                                      errors="replace").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) < 2:
            raise SystemExit(f"{path}:{lineno}: expected '0xADDR size [name]'")
        try:
            va = int(parts[0], 16) if parts[0].lower().startswith("0x") else int(parts[0], 16)
            size = int(parts[1], 0)
        except ValueError as exc:
            raise SystemExit(f"{path}:{lineno}: {exc}") from exc
        name = parts[2] if len(parts) > 2 else f"f_{va:08x}"
        out.append((va, size, name))
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--image", required=True)
    ap.add_argument("--funcs", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--block", action="store_true",
                    help="lift one basic block per entry (closure mode)")
    ap.add_argument("--only", nargs="*", default=None,
                    help="optional VA filter (hex)")
    args = ap.parse_args(argv)

    if args.block:
        os.environ["WC3_LIFT_BLOCK"] = "1"
    else:
        os.environ.pop("WC3_LIFT_BLOCK", None)

    img = PeImage(args.image)
    lifter32.IMAGE_BASE = img.base
    lifter = Lifter(args.image, img.image_size, img.read_va)
    lifter.reloc_vas = img.reloc_vas()

    wanted = None
    if args.only:
        wanted = {int(x, 16) for x in args.only}

    bounds = load_bounds(args.funcs)
    if wanted is not None:
        bounds = [b for b in bounds if b[0] in wanted]

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    written: list[int] = []
    with out_path.open("w", encoding="utf-8", newline="\n") as f:
        f.write("/* AUTO-GENERATED by tools/lift (lift_rev=%d); do not edit. */\n" % LIFT_REV)
        f.write("/* image: %s sha256:%s */\n" % (Path(args.image).name, img.sha256()))
        f.write('#include "cpu.h"\n\n')
        for va, size, _name in bounds:
            if not img.is_code(va):
                continue
            if size <= 0:
                continue
            try:
                code = img.read_va(va, size)
                body = lifter.lift_function(code, va)
            except Exception as exc:  # noqa: BLE001 - worker must report the VA
                print(f"lift failed at {va:#010x} size {size:#x}: {exc}",
                      file=sys.stderr)
                raise
            f.write(body)
            f.write("\n\n")
            written.append(va)

    # A list header next to the C file is what the dispatcher consumes.  It is
    # generated from what was actually emitted, not from the input catalog.
    list_path = out_path.with_suffix(".list.h")
    with list_path.open("w", encoding="ascii", newline="\n") as f:
        f.write("/* AUTO-GENERATED by tools/lift; do not edit. */\n")
        f.write("#define LIFTED_FUNCS(X) \\\n")
        for i, va in enumerate(written):
            sep = "" if i + 1 == len(written) else " \\"
            f.write(f"    X({va:08X}){sep}\n")
        if not written:
            f.write("\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
