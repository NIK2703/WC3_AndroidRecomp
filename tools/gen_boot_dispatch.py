#!/usr/bin/env python3
"""Generate the boot dispatcher's LIFTED_FUNCS list and hash table.

The input is the corpus VA list (one X(006A0A0A) per line, as emitted by the
lifter).  The default prefixes are 004 (war3.exe) and 350 (Storm.dll at its
Android image base); the multi-module relifted build passes every prefix from
corpus_manifest.json.

O-24: dispatch_boot.c used to rebuild its open-addressing table from g_lift[]
on every startup.  The same table is now emitted here as a constant C array.
The hash function, probe order and slot payload (g_lift index + 1) are copied
from that runtime builder unchanged; only the publication point moved from
wc3_dispatch_init() to .rodata.  No speed claim is made until G-10/PM-19
measures cold_start.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

VA_RE = re.compile(r"X\(([0-9A-Fa-f]{8})\)")

# Frozen P1-5 hash parameters.  These used to live next to the runtime builder
# in dispatch_boot.c; the generated header now owns the definition so the
# constant table and find_lifted() cannot disagree about the slot count.
LIFT_HASH_BITS = 19
LIFT_HASH_SIZE = 1 << LIFT_HASH_BITS
LIFT_HASH_MULTIPLIER = 2654435761


def build_hash_slots(values: list[str]) -> dict[int, int]:
    """Reproduce dispatch_boot.c's insertion loop exactly.

    The table starts zeroed, then each value is inserted in g_lift order with
    the Knuth multiplicative hash and linear probing.  The payload is i + 1 so
    that zero keeps meaning "empty", as in the old g_lift_hash convention.
    """
    slots: dict[int, int] = {}
    for index, value in enumerate(values):
        h = ((int(value, 16) * LIFT_HASH_MULTIPLIER) & 0xFFFFFFFF) >> (
            32 - LIFT_HASH_BITS
        )
        while h in slots:
            h = (h + 1) & (LIFT_HASH_SIZE - 1)
        slots[h] = index + 1
    if len(slots) != len(values):
        raise SystemExit("hash table lost entries; refusing to write a bad table")
    return slots


def render_hash_header(values: list[str]) -> str:
    slots = build_hash_slots(values)
    lines = [
        "/* AUTO-GENERATED by tools/gen_boot_dispatch.py - do not edit */",
        "/* O-24: constant open-addressing hash for the boot dispatcher.",
        " *",
        " * This is the table wc3_dispatch_init() used to rebuild from g_lift[]",
        f" * on every start: {len(values)} entries, {LIFT_HASH_BITS} hash bits,",
        f" * g_lift_hash[{LIFT_HASH_SIZE}] slots.  The Knuth multiplier, the",
        " * linear probe order, the g_lift index payload (i + 1) and",
        " * find_lifted() are unchanged; only publication moved from runtime",
        " * construction to .rodata.",
        " * No speed claim is made until G-10/PM-19 measures cold_start. */",
        "#ifndef WC3_BOOT_DISPATCH_HASH_H",
        "#define WC3_BOOT_DISPATCH_HASH_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define LIFT_HASH_BITS {LIFT_HASH_BITS}",
        "#define LIFT_HASH_SIZE (1u << LIFT_HASH_BITS)",
        "",
        "static const uint32_t g_lift_hash[LIFT_HASH_SIZE] = {",
    ]
    for h in sorted(slots):
        lines.append(f"    [0x{h:05X}] = {slots[h]}u,")
    lines.extend(["};", "", "#endif", ""])
    return "\n".join(lines)


def self_test() -> int:
    """Check the generator against the lookup loop it replaced.

    No project build is involved.  The test forces one real 19-bit hash
    collision, so the linear-probe path and the ``i + 1`` payload are both
    exercised instead of only the happy path.
    """
    seen: dict[int, str] = {}
    first = second = ""
    for i in range(1_000_000):
        value = f"{0x00400000 + i * 4:08X}"
        h = ((int(value, 16) * LIFT_HASH_MULTIPLIER) & 0xFFFFFFFF) >> (
            32 - LIFT_HASH_BITS
        )
        if h in seen:
            first, second = seen[h], value
            break
        seen[h] = value
    if not first:
        raise SystemExit("self-test: could not find a hash collision")

    slots = build_hash_slots([first, second])
    if len(slots) != 2 or sorted(slots.values()) != [1, 2]:
        raise SystemExit(f"self-test: bad collision slots: {slots}")

    values = [f"{0x00400000 + i * 4:08X}" for i in range(4096)]
    slots = build_hash_slots(values)
    if len(slots) != len(values):
        raise SystemExit("self-test: hash table lost entries")
    if sorted(slots.values()) != list(range(1, len(values) + 1)):
        raise SystemExit("self-test: payload is not g_lift index + 1")
    for index, value in enumerate(values):
        h = ((int(value, 16) * LIFT_HASH_MULTIPLIER) & 0xFFFFFFFF) >> (
            32 - LIFT_HASH_BITS
        )
        while h in slots and slots[h] != index + 1:
            h = (h + 1) & (LIFT_HASH_SIZE - 1)
        if slots.get(h) != index + 1:
            raise SystemExit(
                f"self-test: lookup failed for {value} at slot 0x{h:05X}")
    header = render_hash_header(values)
    rendered = len(re.findall(r"^\s*\[0x[0-9A-F]+\] = \d+u,$", header, re.M))
    if rendered != len(values) or "g_lift_hash[LIFT_HASH_SIZE]" not in header:
        raise SystemExit("self-test: rendered header does not match the table")
    print(f"gen_boot_dispatch self-test: OK ({len(values)} entries, "
          f"collision {first}/{second})")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--list", type=Path)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument(
        "--hash-out",
        type=Path,
        default=None,
        help="hash header path (default: boot_dispatch_hash.h next to --out)",
    )
    ap.add_argument("--prefix", action="append", default=[])
    ap.add_argument("--expect-count", type=int, default=None)
    args = ap.parse_args()

    if args.self_test:
        return self_test()
    if args.list is None or args.out is None:
        ap.error("--list and --out are required unless --self-test is given")

    prefixes = tuple(args.prefix) if args.prefix else ("004", "350")
    text = args.list.read_text(encoding="ascii", errors="ignore")
    seen: set[str] = set()
    for value in VA_RE.findall(text):
        value = value.upper()
        if value.startswith(prefixes):
            seen.add(value)

    values = sorted(seen, key=lambda v: int(v, 16))
    if not values:
        raise SystemExit(f"no VAs with prefixes {prefixes} in {args.list}")
    if args.expect_count is not None and len(values) != args.expect_count:
        raise SystemExit(
            f"dispatcher list has {len(values)} functions, "
            f"manifest says {args.expect_count}")
    if len(values) > LIFT_HASH_SIZE:
        raise SystemExit(
            f"dispatcher list has {len(values)} functions, "
            f"hash table has only {LIFT_HASH_SIZE} slots")

    lines = [
        "/* AUTO-GENERATED by tools/gen_boot_dispatch.py - do not edit */",
        f"/* {len(values)} functions: prefixes {', '.join(prefixes)} */",
        "#ifndef WC3_BOOT_DISPATCH_LIST_H",
        "#define WC3_BOOT_DISPATCH_LIST_H",
        "",
        "#define LIFTED_FUNCS(X) \\",
    ]
    for i, value in enumerate(values):
        suffix = " \\" if i + 1 != len(values) else ""
        lines.append(f"    X({value}){suffix}")
    lines.extend(["", "#endif", ""])

    hash_out = args.hash_out
    if hash_out is None:
        # Keep tools/build_boot_probe.ps1 working: it only passes --out and
        # already has the output directory on its include path.
        hash_out = args.out.parent / "boot_dispatch_hash.h"

    # Render both files before writing either one, so a table error cannot
    # leave the list and hash headers out of sync.
    list_text = "\n".join(lines)
    hash_text = render_hash_header(values)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    hash_out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(list_text, encoding="ascii")
    hash_out.write_text(hash_text, encoding="ascii")
    print(f"wrote {args.out} ({len(values)} functions)")
    print(f"wrote {hash_out} ({LIFT_HASH_SIZE} slots)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
