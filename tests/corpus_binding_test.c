#ifdef _WIN32
static int host_reserve(void *ctx, uint32_t base, uint32_t size)
{
    (void)ctx;
    return VirtualAlloc((void *)(uintptr_t)base, size, MEM_RESERVE,
                        PAGE_NOACCESS) ? 0 : -1;
}

static int host_commit(void *ctx, uint32_t base, uint32_t size)
{
    (void)ctx;
    return VirtualAlloc((void *)(uintptr_t)base, size, MEM_COMMIT,
                        PAGE_READWRITE) ? 0 : -1;
}

static int host_decommit(void *ctx, uint32_t base, uint32_t size)
{
    (void)ctx;
    return VirtualFree((void *)(uintptr_t)base, size, MEM_DECOMMIT) ? 0 : -1;
}

static int host_release(void *ctx, uint32_t base, uint32_t size)
{
    (void)ctx;
    (void)size;
    return VirtualFree((void *)(uintptr_t)base, 0, MEM_RELEASE) ? 0 : -1;
}

static int host_protect(void *ctx, uint32_t base, uint32_t size, uint32_t prot)
{
    (void)ctx;
    DWORD native = (prot & WC3_MEM_EXEC) ? PAGE_EXECUTE_READWRITE
                                         : PAGE_READWRITE;
    DWORD old;
    return VirtualProtect((void *)(uintptr_t)base, size, native, &old) ? 0 : -1;
}
#else
static int host_reserve(void *ctx, uint32_t base, uint32_t size)
{
    (void)ctx;
    int flags = MAP_PRIVATE | MAP_ANONYMOUS;
#ifdef MAP_FIXED_NOREPLACE
    flags |= MAP_FIXED_NOREPLACE;
#endif
    void *want = (void *)(uintptr_t)base;
    void *p = mmap(want, size, PROT_NONE, flags, -1, 0);
#ifdef MAP_FIXED_NOREPLACE
    if (p == MAP_FAILED && errno == EINVAL) {
        /* Old kernel: a plain hint cannot clobber an existing mapping. */
        p = mmap(want, size, PROT_NONE, MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
    }
#endif
    if (p == MAP_FAILED) return -1;
    if (p != want) {
        (void)munmap(p, size);
        return -1;
    }
    return 0;
}

static int host_commit(void *ctx, uint32_t base, uint32_t size)
{
    (void)ctx;
    return mprotect((void *)(uintptr_t)base, size,
                    PROT_READ | PROT_WRITE) == 0 ? 0 : -1;
}

static int host_decommit(void *ctx, uint32_t base, uint32_t size)
{
    (void)ctx;
    (void)base;
    (void)size;
    return 0;
}

static int host_release(void *ctx, uint32_t base, uint32_t size)
{
    (void)ctx;
    return munmap((void *)(uintptr_t)base, size) == 0 ? 0 : -1;
}

static int host_protect(void *ctx, uint32_t base, uint32_t size, uint32_t prot)
{
    (void)ctx;
    int native = (prot & WC3_MEM_READ ? PROT_READ : 0) |
                 (prot & WC3_MEM_WRITE ? PROT_WRITE : 0) |
                 (prot & WC3_MEM_EXEC ? PROT_EXEC : 0);
    return mprotect((void *)(uintptr_t)base, size, native) == 0 ? 0 : -1;
}
#endif

/* ------------------------------------------------------------------ file */

typedef struct HostFile {
    FILE *fp;
} HostFile;

static int host_file_open(void *ctx, const char *path, int flags,
                          uintptr_t *out)
{
    (void)ctx;
    if (!path || !out || (flags & WC3_FILE_READ) == 0) return -1;
    FILE *fp = fopen(path, "rb");
    if (!fp) return -1;
    HostFile *file = (HostFile *)malloc(sizeof *file);
    if (!file) {
        (void)fclose(fp);
        return -1;
    }
    file->fp = fp;
    *out = (uintptr_t)file;
    return 0;
}

static int host_file_read(void *ctx, uintptr_t handle, void *buf, uint32_t len,
                          uint32_t *read)
{
    (void)ctx;
    HostFile *file = (HostFile *)(uintptr_t)handle;
    if (!file || !file->fp || !read) return -1;
    size_t got = fread(buf, 1, len, file->fp);
    *read = (uint32_t)got;
    return got == len && !ferror(file->fp) ? 0 : -1;
}

static int host_file_seek(void *ctx, uintptr_t handle, int64_t offset,
                          int whence, uint64_t *pos)
{
    (void)ctx;
    HostFile *file = (HostFile *)(uintptr_t)handle;
    if (!file || !file->fp) return -1;
    /* Wc3FileApi uses the Win32 0/1/2 values; the Android platform maps them
     * the same way. */
    int native = whence == 0 ? SEEK_SET : (whence == 1 ? SEEK_CUR : SEEK_END);
    if (fseek(file->fp, (long)offset, native) != 0) return -1;
    long at = ftell(file->fp);
    if (at < 0) return -1;
    if (pos) *pos = (uint64_t)at;
    return 0;
}

static int host_file_size(void *ctx, uintptr_t handle, uint64_t *size)
{
    (void)ctx;
    HostFile *file = (HostFile *)(uintptr_t)handle;
    if (!file || !file->fp || !size) return -1;
    long at = ftell(file->fp);
    if (at < 0 || fseek(file->fp, 0, SEEK_END) != 0) return -1;
    long end = ftell(file->fp);
    (void)fseek(file->fp, at, SEEK_SET);
    if (end < 0) return -1;
    *size = (uint64_t)end;
    return 0;
}

static int host_file_close(void *ctx, uintptr_t handle)
{
    (void)ctx;
    HostFile *file = (HostFile *)(uintptr_t)handle;
    if (!file) return -1;
    if (file->fp) (void)fclose(file->fp);
    free(file);
    return 0;
}

static void platform_init(Wc3Platform *platform)
{
    memset(platform, 0, sizeof *platform);
    platform->mem.reserve = host_reserve;
    platform->mem.commit = host_commit;
    platform->mem.decommit = host_decommit;
    platform->mem.release = host_release;
    platform->mem.protect = host_protect;
    platform->file.open = host_file_open;
    platform->file.read = host_file_read;
    platform->file.seek = host_file_seek;
    platform->file.size = host_file_size;
    platform->file.close = host_file_close;
}

/* ------------------------------------------------------------------- HLE */

static uint32_t hle_calls;

static uint32_t fake_hle(void *user, const char *dll, const char *name,
                         uint16_t ordinal)
{
    (void)user;
    (void)dll;
    (void)name;
    (void)ordinal;
    hle_calls++;
    return 0x7F000000u + hle_calls * 0x10u;
}

/* ------------------------------------------------------------------ main */

typedef struct ModuleDesc {
    const char *dll;
    const char *file;
    uint32_t base;
} ModuleDesc;

static const ModuleDesc MODULES[] = {
    {"war3.exe", "war3.exe", 0x00400000u},
    {"game.dll", "game.dll", 0x6F000000u},
    {"Storm.dll", "Storm_a35.dll", 0x35000000u},
    {"Mss32.dll", "Mss32_a35.dll", 0x35100000u},
    {"Mssfast.m3d", "Mssfast_a35.m3d", 0x35200000u},
    {"Mp3dec.asi", "Mp3dec_a35.asi", 0x35300000u},
    {"ijl15.dll", "ijl15.dll", 0x60000000u},
};

#define MODULE_COUNT (sizeof MODULES / sizeof MODULES[0])

static int file_exists(const char *path)
{
    FILE *fp = fopen(path, "rb");
    if (!fp) return 0;
    (void)fclose(fp);
    return 1;
}

int main(int argc, char **argv)
{
    const char *dir = argc > 1 ? argv[1] : getenv("WC3_CORPUS_DIR");
    if (!dir || !*dir) dir = "build/corpus-inputs";

    char path[MODULE_COUNT][1024];
    for (size_t i = 0; i < MODULE_COUNT; i++) {
        int n = snprintf(path[i], sizeof path[i], "%s/%s", dir,
                         MODULES[i].file);
        if (n <= 0 || (size_t)n >= sizeof path[i]) {
            printf("corpus binding: FAIL path too long\n");
            return 1;
        }
        if (!file_exists(path[i])) {
            printf("corpus binding: unavailable (%s missing)\n", path[i]);
            return 2;
        }
    }

    Wc3Platform platform;
    platform_init(&platform);
    if (wc3_guest_memory_init(&platform) != 0) {
        printf("corpus binding: FAIL cannot map the guest core arenas\n");
        return 1;
    }

    Wc3ModuleRegistry registry;
    wc3_module_registry_init(&registry);

    /* The header requires the descriptors and their paths to outlive the
     * registry; keep both in main's storage. */
    Wc3ModuleDesc desc[MODULE_COUNT];
    Wc3PeImage image[MODULE_COUNT];
    memset(image, 0, sizeof image);
    for (size_t i = 0; i < MODULE_COUNT; i++) {
        desc[i].dll = MODULES[i].dll;
        desc[i].path = path[i];
        desc[i].base = MODULES[i].base;
        desc[i].allow_relocate = 0;
        if (wc3_module_load(&registry, &platform, &desc[i], &image[i]) != 0) {
            printf("corpus binding: FAIL cannot load %s at %08X\n",
                   MODULES[i].dll, MODULES[i].base);
            return 1;
        }
        check(image[i].base == MODULES[i].base, "module mapped at target base");
    }
    check(registry.count == MODULE_COUNT, "all corpus modules registered");

    Wc3BindStats stats;
    wc3_module_stats_init(&stats);
    if (wc3_module_bind_all(&registry, fake_hle, NULL, &stats) != 0) {
        printf("corpus binding: FAIL unresolved import\n");
        fails++;
    }
    check(stats.bound_module == EXPECTED_MODULE_IMPORTS,
          "428 imports bound to lifted modules");
    check(stats.bound_hle == EXPECTED_HLE_IMPORTS,
          "1468 imports bound to HLE");
    check(stats.missing == EXPECTED_MISSING, "no unresolved imports");
    check(stats.export_missing == 0u, "no missing lifted export");
    check(stats.bound_module + stats.bound_hle + stats.missing ==
              EXPECTED_MODULE_IMPORTS + EXPECTED_HLE_IMPORTS,
          "every import of the seven files is accounted for");
    check(hle_calls == EXPECTED_HLE_IMPORTS, "HLE call count matches");

    /* A named lifted import, an ordinal lifted import and an OS import. */
    Wc3Module *mss = wc3_module_find(&registry, "MSS32.DLL");
    Wc3Module *storm = wc3_module_find(&registry, "storm.dll");
    check(mss != NULL && storm != NULL, "lookup of loaded modules");
    if (mss) {
        uint32_t want = wc3_pe_export(&mss->image, SAMPLE_NAME);
        check(want != 0u, "sample named export exists");
        check(load32(SAMPLE_NAME_SLOT) == want,
              "sample named IAT points at lifted export");
    }
    if (storm) {
        uint32_t want = wc3_pe_export_ordinal(&storm->image, SAMPLE_ORDINAL);
        check(want != 0u, "sample ordinal export exists");
        check(load32(SAMPLE_ORDINAL_SLOT) == want,
              "sample ordinal IAT points at lifted export");
    }
    uint32_t hle = load32(SAMPLE_HLE_SLOT);
    check(hle >= 0x7F000000u &&
              hle < 0x7F000000u + 65536u * 16u,
          "OS import points into the HLE thunk window");

    verify_all_iat(&registry, image, MODULE_COUNT);

#if WC3_DEBUG
    check(stats.first_missing_dll[0] == '\0', "no first missing diagnostic");
    check(stats.first_export_missing_dll[0] == '\0',
          "no export mismatch diagnostic");
#endif

    for (size_t i = 0; i < MODULE_COUNT; i++)
        (void)wc3_guest_unmap(image[i].base, image[i].span);

    if (fails) {
        printf("corpus binding: %d failure(s)\n", fails);
        return 1;
    }
    printf("corpus binding: OK (7 modules, %u lifted, %u HLE)\n",
           stats.bound_module, stats.bound_hle);
    return 0;
}
