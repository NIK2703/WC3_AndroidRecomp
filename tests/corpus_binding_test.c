/*
 * corpus_binding_test.c - the real 1.27.1.7085 corpus through the module
 * registry.
 *
 * The synthetic module_registry_test pins the resolver semantics with hand
 * built PE layouts.  This test is the other half: it maps the seven rebased
 * corpus files at their fixed guest bases with the production wc3_pe_load(),
 * registers them in Wc3ModuleRegistry and rewrites every IAT with
 * wc3_module_bind_all().  The expected counts come from the pinned fixture:
 * 428 imports are exported by a loaded lifted module and the remaining 1468
 * imports of those seven files must reach the HLE resolver.
 *
 * The corpus is licensed and lives in build/corpus-inputs (generated by
 * corpusinput prepare).  When it is absent the test reports `unavailable`
 * instead of passing.  The fixture is pinned, so a corpus change that moves
 * one of the sample slots is a test failure, not a silent skip.
 */
#include "guest_memory.h"
#include "guest_modules.h"
#include "platform.h"

#include <errno.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#ifdef _WIN32
#include <windows.h>
#else
#include <sys/mman.h>
#include <unistd.h>
#endif

#define EXPECTED_MODULE_IMPORTS 428u
#define EXPECTED_HLE_IMPORTS 1468u
#define EXPECTED_MISSING 0u

/* war3.exe samples from config/imports.1.27b.json (lifted, lifted ordinal,
 * HLE).  A rebase changes only ImageBase, so these slot VAs stay valid. */
#define SAMPLE_NAME_SLOT 0x0045C644u  /* mss32.dll!_AIL_open_stream@12 */
#define SAMPLE_NAME "_AIL_open_stream@12"
#define SAMPLE_ORDINAL_SLOT 0x0045C370u /* Storm.dll ordinal 279 */
#define SAMPLE_ORDINAL 279u
#define SAMPLE_HLE_SLOT 0x0045C17Cu    /* KERNEL32.dll!Sleep */

static int fails;

static void check(int condition, const char *what)
{
    if (!condition) {
        printf("FAIL %s\n", what);
        fails++;
    }
}

static uint32_t load32(uint32_t va)
{
    uint32_t value;
    memcpy(&value, (const void *)(uintptr_t)va, sizeof value);
    return value;
}

/* PE32 import descriptor: OriginalFirstThunk, TimeDateStamp, ForwarderChain,
 * Name, FirstThunk. */
#define IMPORT_DESC_SIZE 20u
#define IMPORT_NAME_DESC 12u
#define IMPORT_FIRST_THUNK 16u

static void verify_all_iat(Wc3ModuleRegistry *registry, const Wc3PeImage *images,
                           size_t count)
{
    uint32_t lifted = 0;
    uint32_t hle = 0;
    uint32_t without_oft = 0;

    for (size_t m = 0; m < count; m++) {
        const Wc3PeImage *image = &images[m];
        if (image->import_rva == 0u) continue;
        uint32_t desc = image->base + image->import_rva;

        for (uint32_t i = 0;; i++) {
            uint32_t at = desc + i * IMPORT_DESC_SIZE;
            uint32_t oft = load32(at);
            uint32_t name_rva = load32(at + IMPORT_NAME_DESC);
            uint32_t iat = load32(at + IMPORT_FIRST_THUNK);
            if (name_rva == 0u && oft == 0u && iat == 0u) break;
            if (name_rva == 0u || iat == 0u || oft == 0u) {
                without_oft++;
                continue;
            }

            const char *dll =
                (const char *)(uintptr_t)(image->base + name_rva);
            Wc3Module *target = wc3_module_find(registry, dll);

            for (uint32_t j = 0;; j++) {
                uint32_t thunk = load32(image->base + oft + j * 4u);
                if (thunk == 0u) break;
                uint32_t slot = load32(image->base + iat + j * 4u);

                if (target) {
                    uint32_t want;
                    if (thunk & 0x80000000u) {
                        want = wc3_pe_export_ordinal(
                            &target->image, (uint16_t)(thunk & 0xFFFFu));
                    } else {
                        const char *symbol = (const char *)(uintptr_t)(
                            image->base + (thunk & 0x7FFFFFFFu) + 2u);
                        want = wc3_pe_export(&target->image, symbol);
                    }
                    if (want != 0u) {
                        check(slot == want,
                              "every lifted IAT slot points at its export");
                        lifted++;
                        continue;
                    }
                    /* A loaded module with a missing export is a lift defect;
                     * the stats check below names it separately. */
                }

                check(slot >= 0x7F000000u &&
                          slot < 0x7F000000u + 65536u * 16u,
                      "every remaining IAT slot points into the HLE window");
                hle++;
            }
        }
    }

    check(lifted == EXPECTED_MODULE_IMPORTS,
          "full IAT audit counted 428 lifted imports");
    check(hle == EXPECTED_HLE_IMPORTS,
          "full IAT audit counted 1468 HLE imports");
    check(without_oft == 0u, "every import descriptor has OriginalFirstThunk");
}

